"""
Writes content/photos.ts — the registry of the inner pages' photographs — from the prompt sheet
brand/fotostijl/paginas-fotos.md (id, web format and the alt text in three languages).

    python scripts/build-photo-registry.py

Run it again after editing the sheet. The files themselves come from scripts/export-photos.py.
"""
import json
import os
import re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SHEET = os.path.join(ROOT, "brand", "fotostijl", "paginas-fotos.md")
OUT = os.path.join(ROOT, "content", "photos.ts")


def parse(md):
    items = []
    for block in re.split(r"^### ", md, flags=re.M)[1:]:
        pid = block.split("\n", 1)[0].strip()
        if not re.fullmatch(r"[a-z0-9-]+", pid):
            continue
        ratio = re.search(r"\*\*Formaat:\*\*\s*([0-9]+:[0-9]+)", block)
        alt = {}
        for lang in ("EN", "NL", "AR"):
            m = re.search(rf"\*\*Alt {lang}:\*\*\s*(.+)", block)
            alt[lang.lower()] = m.group(1).strip() if m else ""
        if ratio:
            items.append((pid, ratio.group(1), alt))
    return items


def main():
    items = parse(open(SHEET, encoding="utf8").read())
    lines = [
        "import type { T } from \"./pages/types\";",
        "",
        "/**",
        " * The inner pages' photographs (house style \"Known Weight\", brand/fotostijl/DUKAAT-fotostijl.md).",
        " * Generated by scripts/build-photo-registry.py from brand/fotostijl/paginas-fotos.md — edit the sheet, not this file.",
        " * Files: public/photos/pages/<id>.jpg (scripts/export-photos.py).",
        " */",
        "export type PhotoMeta = { ratio: \"21:9\" | \"3:2\" | \"4:5\"; alt: T };",
        "",
        "export const photos: Record<string, PhotoMeta> = {",
    ]
    for pid, ratio, alt in items:
        lines.append(f"  {json.dumps(pid)}: {{ ratio: {json.dumps(ratio)}, alt: {{ en: {json.dumps(alt['en'], ensure_ascii=False)}, nl: {json.dumps(alt['nl'], ensure_ascii=False)}, ar: {json.dumps(alt['ar'], ensure_ascii=False)} }} }},")
    lines.append("};")
    lines.append("")
    open(OUT, "w", encoding="utf8", newline="\n").write("\n".join(lines))
    print(f"{len(items)} photos -> content/photos.ts")


if __name__ == "__main__":
    main()
